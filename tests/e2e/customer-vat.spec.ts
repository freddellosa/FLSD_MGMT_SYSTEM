import {test, expect, type Page} from '@playwright/test';
const nav = (page: Page, name: string) => page.getByRole('navigation').getByRole('button', {name, exact: true}).click();
test('customer VAT setting controls new trip tax while retaining historical charges', async ({page}) => {
  await page.goto('/'); await page.getByLabel('Demo role').selectOption('ADMIN'); await nav(page, 'Customers');
  await page.getByRole('button', {name: 'Edit customer Santos Family', exact: true}).click();
  await expect(page.getByLabel('Customer VAT status')).toHaveValue('UNREVIEWED');
  await page.getByLabel('Customer VAT status').selectOption('VAT'); await page.getByRole('button', {name: 'Save customer', exact: true}).click();
  await nav(page, 'Trips'); await page.getByRole('button', {name: 'New trip', exact: true}).click();
  let dialog = page.getByRole('dialog');
  await dialog.getByRole('combobox', {name: 'Charge to / customer', exact: true}).selectOption('c1');
  await expect(dialog.getByLabel('Enter VAT for this trip')).toBeChecked(); await expect(dialog.getByLabel('Enter VAT for this trip')).toBeDisabled();
  await dialog.getByLabel('Destination details / stops', {exact: true}).fill('Customer VAT regression trip');
  await dialog.getByLabel('Base amount (PHP)', {exact: true}).fill('1000'); await dialog.getByLabel('OT fee (PHP)', {exact: true}).fill('100');
  await dialog.getByLabel('Fuel (PHP)', {exact: true}).fill('500'); await dialog.getByLabel('VAT treatment', {exact: true}).selectOption('ADDED');
  await expect(dialog.getByLabel('VAT amount (PHP)', {exact: true})).toHaveValue('132.00');
  await expect(dialog.getByLabel('Total trip amount', {exact: true})).toContainText('1,732.00');
  await dialog.getByLabel('VAT treatment', {exact: true}).selectOption('INCLUDED');
  await expect(dialog.getByLabel('VAT amount (PHP)', {exact: true})).toHaveValue('117.86');
  await expect(dialog.getByLabel('Total trip amount', {exact: true})).toContainText('1,600.00');
  await dialog.getByLabel('VAT treatment', {exact: true}).selectOption('ADDED'); await dialog.getByRole('button', {name: 'Create demo trip', exact: true}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await nav(page, 'Customers'); await page.getByRole('button', {name: 'Edit customer Santos Family', exact: true}).click();
  await expect(page.getByLabel('Customer VAT status')).toHaveValue('VAT');
  await page.getByLabel('Customer VAT status').selectOption('NON_VAT'); await page.getByRole('button', {name: 'Save customer', exact: true}).click();
  await nav(page, 'Trips'); await page.getByLabel('Search trips').fill('Customer VAT regression trip');
  await expect(page.getByRole('table', {name: 'Trip register'}).locator('tbody tr')).toContainText('1,732.00');
  await page.getByRole('table', {name: 'Trip register'}).locator('tbody tr').getByRole('button').click();
  await page.getByRole('button', {name: 'Edit trip', exact: true}).click();
  dialog = page.getByRole('dialog');
  await expect(dialog.getByLabel('Enter VAT for this trip')).toBeChecked();
  await expect(dialog.getByLabel('VAT amount (PHP)', {exact: true})).toHaveValue('132.00');
  await dialog.getByLabel('Trip change reason', {exact: true}).fill('Retain recorded charges after customer classification change');
  await dialog.getByRole('button', {name: 'Save trip changes', exact: true}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.getByRole('table', {name: 'Trip register'}).locator('tbody tr')).toContainText('1,732.00');
  await page.getByRole('button', {name: 'New trip', exact: true}).click(); dialog = page.getByRole('dialog');
  await dialog.getByRole('combobox', {name: 'Charge to / customer', exact: true}).selectOption('c1');
  await expect(dialog.getByLabel('Enter VAT for this trip')).not.toBeChecked(); await expect(dialog.getByLabel('Enter VAT for this trip')).toBeDisabled();
  await expect(dialog.getByLabel('VAT treatment', {exact: true})).toHaveCount(0);
});

test('customer validation failure retains the selected VAT classification and other input', async ({page}) => {
  await page.goto('/'); await page.getByLabel('Demo role').selectOption('ADMIN'); await nav(page, 'Customers');
  await page.getByRole('button', {name: 'Edit customer Santos Family', exact: true}).click();
  await page.getByLabel('Customer name', {exact: true}).fill('Northstar Logistics'); await page.getByLabel('Customer VAT status').selectOption('NON_VAT');
  await page.getByRole('button', {name: 'Save customer', exact: true}).click();
  const dialog = page.getByRole('dialog', {name: 'Customer editor', exact: true});
  await expect(dialog.getByRole('alert')).toBeVisible(); await expect(dialog.getByLabel('Customer name', {exact: true})).toHaveValue('Northstar Logistics');
  await expect(dialog.getByLabel('Customer VAT status')).toHaveValue('NON_VAT');
  await dialog.getByLabel('Customer name', {exact: true}).fill('Santos Family'); await dialog.getByRole('button', {name: 'Save customer', exact: true}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button', {name: 'Edit customer Santos Family', exact: true}).click();
  await expect(page.getByLabel('Customer VAT status')).toHaveValue('NON_VAT');
});
